def add_free_short(t):
    if "бесплат" in t.lower() or "в подарок" in t:
        return t
    if t.endswith(TAIL):
        new = t[: -len(TAIL)] + FREE_SHORT + " " + TAIL
    else:
        new = t.rstrip() + " " + FREE_SHORT
    return new if len(new) <= 250 else t


def free_long_for(n):
    if 5 <= n <= 10:
        return "Консультация терапевта, ортопеда или хирурга-имплантолога с разбором снимка бесплатная."
    if 11 <= n <= 17:
        return "Консультация стоматолога-терапевта бесплатная."
    if 18 <= n <= 35:
        return "Консультация хирурга-имплантолога бесплатная."
    if 36 <= n <= 55:
        return "Консультация стоматолога-ортопеда бесплатная."
    if 56 <= n <= 63:
        return "Консультация хирурга бесплатная."
    return FREE_LONG


def add_free_long(t, n):
    if "бесплат" in t.lower():
        return t
    line = free_long_for(n)
    i = t.find("Запишитесь кнопкой")
    if i == -1:
        return t.rstrip() + "\n\n" + line
    return t[:i] + line + " " + t[i:]


